_TR_data = {'pet':PET,'empty':Empty}

def get_nearest_T(material:str,band):
    global _TR_data
    Tdict = _TR_data[material.lower()]

    freq = Tdict['f']
    T = Tdict['T']

    T = np.asarray(T)
    freq = np.asarray(freq)
    idx = abs(freq-band).argmin()
    return T[idx]
